import { type ContentMapper, createContentMapper } from '@vue/content-mapper';
import { names } from '@vue/language-core';
import type { Linter, Rule } from 'eslint';
import * as path from 'node:path';
import { LineIndex, SourceMap } from './sourceMap';

interface FileState {
  originalText: string;
  originalLines: LineIndex;
  virtualText: string;
  virtualLines: LineIndex;
  sourceMap: SourceMap;
}

/**
 * Code that language-core generates in front of a template identifier: `__VLS_ctx.foo`,
 * `__VLS_dollars.$attrs`, `__VLS_unwrap(foo, …)`. It has no mapping, so a report on the whole
 * expression would otherwise start in generated code and be dropped.
 */
const identifierPrefixes = [
  `${names.ctx}.`,
  `${names.dollars}.`,
  `${names.unwrap}(`,
];

/** Every name language-core generates, such as `__VLS_export`. */
const generatedNames = new Set<string>(Object.values(names));

let mapper: ContentMapper | undefined;
const files = new Map<string, FileState>();

/**
 * Lints the TypeScript generated by `@vue/content-mapper` instead of the `.vue` file itself, then
 * maps reports back to the original file. Reports on generated code with no original span are
 * dropped.
 */
export const processor: Linter.Processor = {
  meta: {
    name: 'vue-contentmapper',
  },
  supportsAutofix: true,

  preprocess(text, filename) {
    mapper ??= createContentMapper({ name: 'Vue content mapper' });
    const result = mapper.transform({
      fileName: path.resolve(filename),
      content: text,
    });
    files.set(filename, {
      originalText: text,
      originalLines: new LineIndex(text),
      virtualText: result.text,
      virtualLines: new LineIndex(result.text),
      sourceMap: new SourceMap(result.mappings),
    });
    return [{ text: result.text, filename: `0${result.extension}` }];
  },

  postprocess(messageLists, filename) {
    const file = files.get(filename);
    files.delete(filename);
    if (!file) {
      return messageLists.flat();
    }

    const seen = new Set<string>();
    const messages: Linter.LintMessage[] = [];
    for (const message of messageLists.flat()) {
      const mapped = mapMessage(file, message);
      if (!mapped) {
        continue;
      }
      const key = [
        mapped.ruleId,
        mapped.line,
        mapped.column,
        mapped.endLine,
        mapped.endColumn,
        mapped.message,
      ].join('\0');
      if (!seen.has(key)) {
        seen.add(key);
        messages.push(mapped);
      }
    }
    return messages;
  },
};

function mapMessage(
  file: FileState,
  message: Linter.LintMessage,
): Linter.LintMessage | undefined {
  const { originalLines, virtualLines, sourceMap } = file;
  const reportStart = virtualLines.toOffset(message.line, message.column);
  const end =
    message.endLine === undefined
      ? reportStart
      : virtualLines.toOffset(
          message.endLine,
          message.endColumn ?? message.column,
        );
  const start = skipIdentifierPrefix(file, reportStart, end);
  if (isOnGeneratedName(file, start)) {
    return undefined;
  }
  const range = sourceMap.toOriginalRange(start, end);

  if (!range) {
    // A parse error in generated code still means nothing else in the file was linted.
    if (message.fatal) {
      return {
        ...message,
        line: 1,
        column: 1,
        endLine: undefined,
        endColumn: undefined,
        message: `${message.message} (in generated code)`,
      };
    }
    return undefined;
  }

  const { fix, suggestions, ...rest } = message;
  const cleanText = createTextCleaner(file, reportStart, end);
  const startPosition = originalLines.toPosition(range[0]);
  const mapped: Linter.LintMessage = {
    ...rest,
    message: cleanText(message.message),
    line: startPosition.line,
    column: startPosition.column,
  };
  if (message.endLine !== undefined) {
    const endPosition = originalLines.toPosition(range[1]);
    mapped.endLine = endPosition.line;
    mapped.endColumn = endPosition.column;
  }

  if (fix) {
    const mappedFix = mapFix(file, fix);
    if (mappedFix) {
      mapped.fix = mappedFix;
    }
  }
  if (suggestions) {
    const mappedSuggestions = suggestions.flatMap((suggestion) => {
      const mappedFix = mapFix(file, suggestion.fix);
      return mappedFix
        ? [{ ...suggestion, desc: cleanText(suggestion.desc), fix: mappedFix }]
        : [];
    });
    if (mappedSuggestions.length) {
      mapped.suggestions = mappedSuggestions;
    }
  }
  return mapped;
}

interface IdentifierWrapper {
  /** Offset of the wrapped identifier, right after the prefix. */
  identifierStart: number;
  identifierEnd: number;
  /** Offset after the whole wrapper, e.g. after the `)` of `__VLS_unwrap(foo, …)`. */
  wrapperEnd: number;
}

/**
 * The generated wrapper around a template identifier starting at `offset`, if any:
 * `__VLS_ctx.foo` or `__VLS_unwrap(foo, …)`, with an unmapped prefix and a mapped identifier.
 * Text the user wrote is always mapped, so a prefix spelled out in a string literal never matches.
 */
function identifierWrapperAt(
  { virtualText, sourceMap }: FileState,
  offset: number,
): IdentifierWrapper | undefined {
  if (sourceMap.mappingAt(offset)) {
    return undefined;
  }
  for (const prefix of identifierPrefixes) {
    if (!virtualText.startsWith(prefix, offset)) {
      continue;
    }
    const identifier = sourceMap.mappingAt(offset + prefix.length);
    if (!identifier) {
      continue;
    }
    return {
      identifierStart: offset + prefix.length,
      identifierEnd: identifier.generatedEnd,
      wrapperEnd: prefix.endsWith('(')
        ? findClosingParen(virtualText, offset + prefix.length)
        : identifier.generatedEnd,
    };
  }
  return undefined;
}

/**
 * Moves a report start that sits on an identifier wrapper to the identifier, when the report covers
 * more than the wrapper. A report on the wrapper itself has no counterpart in the original and
 * stays dropped.
 */
function skipIdentifierPrefix(file: FileState, start: number, end: number) {
  const wrapper = identifierWrapperAt(file, start);
  return wrapper && end > wrapper.wrapperEnd ? wrapper.identifierStart : start;
}

/**
 * Rules quote the code they report on, so messages on template expressions can read
 * ``Use `Boolean(__VLS_ctx.foo)` instead``. Replaces each identifier wrapper in the report's range
 * with the identifier, unless the original file contains the same text.
 */
function createTextCleaner(file: FileState, start: number, end: number) {
  const { virtualText, originalText } = file;
  const replacements = new Map<string, string>();
  for (const prefix of identifierPrefixes) {
    for (
      let offset = virtualText.indexOf(prefix, start);
      offset !== -1 && offset < end;
      offset = virtualText.indexOf(prefix, offset + 1)
    ) {
      const wrapper = identifierWrapperAt(file, offset);
      if (!wrapper) {
        continue;
      }
      const generated = virtualText.slice(offset, wrapper.wrapperEnd);
      if (!originalText.includes(generated)) {
        replacements.set(
          generated,
          virtualText.slice(wrapper.identifierStart, wrapper.identifierEnd),
        );
      }
    }
  }
  return (text: string) => {
    for (const [generated, identifier] of replacements) {
      text = text.split(generated).join(identifier);
    }
    return text;
  };
}

/**
 * Whether `offset` is in a generated name mapped as a whole to user code, e.g. `__VLS_export`,
 * which maps to the entire `<script setup>` content for type diagnostics. A lint report there
 * (`'__VLS_export' is assigned a value but never used`) is about the generated name.
 */
function isOnGeneratedName(
  { virtualText, sourceMap }: FileState,
  offset: number,
) {
  const mapping = sourceMap.mappingAt(offset);
  return (
    !!mapping &&
    !mapping.verbatim &&
    generatedNames.has(
      virtualText.slice(mapping.generatedStart, mapping.generatedEnd),
    )
  );
}

/** The offset after the `)` closing the call whose arguments start at `offset`. */
function findClosingParen(text: string, offset: number) {
  let depth = 1;
  for (let i = offset; i < text.length; i++) {
    if (text[i] === '(') {
      depth++;
    } else if (text[i] === ')' && --depth === 0) {
      return i + 1;
    }
  }
  return text.length;
}

/**
 * Rules often replace a whole node even when the edit is small, e.g. `!!flag.value` -> `flag.value`.
 * Trimming the text shared by the old and new contents shrinks the fix to the actual edit (deleting
 * `!!`), which is more likely to sit inside a single verbatim mapping.
 */
function mapFix(
  { virtualText, originalText, sourceMap }: FileState,
  fix: Rule.Fix,
): Rule.Fix | undefined {
  let [start, end] = fix.range;
  let text = fix.text;
  const oldText = virtualText.slice(start, end);
  let prefix = 0;
  while (
    prefix < oldText.length &&
    prefix < text.length &&
    oldText[prefix] === text[prefix]
  ) {
    prefix++;
  }
  let suffix = 0;
  while (
    suffix < oldText.length - prefix &&
    suffix < text.length - prefix &&
    oldText[oldText.length - 1 - suffix] === text[text.length - 1 - suffix]
  ) {
    suffix++;
  }
  start += prefix;
  end -= suffix;
  text = text.slice(prefix, text.length - suffix);

  // A rule may copy generated code, such as `__VLS_ctx.foo`, into a replacement for user code.
  for (const name of generatedNames) {
    if (text.includes(name) && !originalText.includes(name)) {
      return undefined;
    }
  }

  const range = sourceMap.toOriginalFixRange(start, end);
  return range ? { range, text } : undefined;
}
